# Функция для добавления заголовка главы
def add_chapter_heading(doc, text, level=1):
    if level == 1:
        heading = doc.add_heading(text, level=0)
        heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
    else:
        heading = doc.add_heading(text, level=level)
    for run in heading.runs:
        run.font.name = 'Times New Roman'
        run.font.size = Pt(16 if level == 1 else 14)
        run.font.bold = True
    return heading

# Функция для добавления абзаца
def add_paragraph(doc, text, bold=False, italic=False, indent=True):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    run.bold = bold
    run.italic = italic
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(0)
    return p

# Функция для добавления таблицы
def add_table_with_data(doc, headers, data, caption):
    # Подпись таблицы
    p = doc.add_paragraph()
    run = p.add_run(caption)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    run.italic = True
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    # Таблица
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    
    # Заголовки
    hdr_cells = table.rows[0].cells
    for i, header in enumerate(headers):
        hdr_cells[i].text = header
        for paragraph in hdr_cells[i].paragraphs:
            for run in paragraph.runs:
                run.font.bold = True
                run.font.name = 'Times New Roman'
                run.font.size = Pt(12)
    
    # Данные
    for row_data in data:
        row_cells = table.add_row().cells
        for i, cell_data in enumerate(row_data):
            row_cells[i].text = str(cell_data)
            for paragraph in row_cells[i].paragraphs:
                for run in paragraph.runs:
                    run.font.name = 'Times New Roman'
                    run.font.size = Pt(12)
    
    doc.add_paragraph()  # Отступ после таблицы
    return table

