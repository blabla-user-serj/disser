add_paragraph(doc, """4) LSTM (Long Short-Term Memory) — архитектура рекуррентной нейронной сети [Hochreiter, Schmidhuber, 1997]. Способна улавливать долгосрочные зависимости, однако требует значительного объёма данных для обучения.""")

