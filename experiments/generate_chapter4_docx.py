add_paragraph(doc, """• MAPE (Mean Absolute Percentage Error) — средняя абсолютная процентная ошибка:""", indent=False)
add_paragraph(doc, """MAPE = (100%/n) × Σ|yᵢ - ŷᵢ|/|yᵢ|""", indent=False)

