add_paragraph(doc, """1) SARIMA (Seasonal AutoRegressive Integrated Moving Average) — классическая статистическая модель временных рядов, являющаяся стандартом де-факто для задач прогнозирования [Box, Jenkins, 1976]. Параметры модели подбирались автоматически по критерию AIC с ограничениями p,q ≤ 3, d ≤ 2.""")

